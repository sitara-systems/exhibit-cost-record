#!/usr/bin/env python3
"""Match Exhibit Cost Record recipients to Experiential Design Index firms
and write a committed crosswalk file into BOTH repos, so each site can
link its firm pages to the other's without either build depending on the
other repo being checked out.

Why (2026-10-12): Search Console shows ~600 ECR firm pages stuck at
"Discovered - currently not indexed" and zero external links into the
dataset, while EDI firm pages are indexed, earn impressions, and are
already being cited by Google AI Mode / Perplexity. A plain cross-link
from each EDI firm page to the same firm's public award records gives
Google a crawl path into the ECR through pages it already trusts, and
gives a reader the cost side of a firm next to its credits.

Matching is deliberately conservative: an ECR recipient matches an EDI
firm only when its normalized legal name equals the normalized EDI
`name` or one of its `aka` names (normalization drops case, punctuation,
"&"/"and", and corporate suffixes like Inc/LLC/Ltd/Corp). No fuzzy
matching -- a wrong "these are the same company" link is worse than a
missing one. Any manual override goes in OVERRIDES / EXCLUDE below.

Usage (re-run whenever either dataset changes, then commit both files):
    python scripts/build_edi_crosswalk.py --edi ../../../ExperientialIndex/experiential-design-index

Writes:
    site/content/edi_crosswalk.json                      (this repo)
    <edi>/data/crosswalks/exhibit-cost-record.json       (EDI repo)
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import export_data  # noqa: E402
import build_firm_pages  # noqa: E402

OUT_ECR = HERE.parent / "content" / "edi_crosswalk.json"

SUFFIXES = r"\b(inc|incorporated|llc|ltd|limited|co|corp|corporation|company|the|pllc|llp|lp|pc|dba)\b"

# (edi_id, ecr_slug) pairs to force-exclude after review.
EXCLUDE: set[tuple[str, str]] = {
    # EDI lists Thinkwell as a TAIT aka, but these Thinkwell Group awards
    # (2016-2023) predate the combination -- held back pending Nathan review.
    ("tait", "thinkwell-group-llc"),
}
# extra {edi_id: [ecr_slug, ...]} links the name rule can't find.
OVERRIDES: dict[str, list[str]] = {}


def norm(name: str) -> str:
    s = name.lower().replace("&", " and ")
    s = re.sub(r"[^a-z0-9 ]+", " ", s)
    s = re.sub(SUFFIXES, " ", s)
    return re.sub(r"\s+", " ", s).strip()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--edi", type=Path, required=True, help="path to the experiential-design-index repo")
    args = ap.parse_args()
    edi_firms_dir = args.edi / "data" / "firms"
    if not edi_firms_dir.is_dir():
        sys.exit(f"not an EDI checkout: {edi_firms_dir} missing")

    records = export_data.normalize()
    by_slug: dict[str, list[dict]] = defaultdict(list)
    variants: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for r in records:
        s = build_firm_pages.slugify(r["recipient"])
        by_slug[s].append(r)
        variants[s][r["recipient"]] += 1
    names_index: dict[str, set[str]] = defaultdict(set)
    for s, vc in variants.items():
        for n in vc:
            names_index[norm(n)].add(s)

    def ecr_summary(slug: str) -> dict:
        recs = by_slug[slug]
        usd = [r["amount"] for r in recs if r.get("amount") and r.get("currency") == "USD"]
        years = sorted({r["year"] for r in recs if r.get("year")})
        return {
            "slug": slug,
            "name": build_firm_pages.choose_display_name(variants[slug]),
            "records": len(recs),
            "total_usd": round(sum(usd)) if usd else None,
            "years": [years[0], years[-1]] if years else None,
        }

    edi_to_ecr: dict[str, list[dict]] = {}
    ecr_to_edi: dict[str, dict] = {}
    for path in sorted(edi_firms_dir.glob("*.yaml")):
        if path.name.startswith("_"):
            continue
        firm = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(firm, dict) or not firm.get("id"):
            continue
        fid = firm["id"]
        keys = [firm["name"], *(firm.get("aka") or [])]
        hits: set[str] = set(OVERRIDES.get(fid, []))
        for k in keys:
            hits |= names_index.get(norm(k), set())
        hits = {s for s in hits if (fid, s) not in EXCLUDE and s in by_slug}
        if not hits:
            continue
        edi_to_ecr[fid] = sorted((ecr_summary(s) for s in hits), key=lambda e: -e["records"])
        for s in hits:
            ecr_to_edi[s] = {"id": fid, "name": firm["name"]}

    stamp = dt.date.today().isoformat()
    note = "Generated by exhibit-cost-record/site/scripts/build_edi_crosswalk.py -- do not hand-edit; re-run it."
    OUT_ECR.write_text(json.dumps({"generated": stamp, "note": note, "ecr_to_edi": dict(sorted(ecr_to_edi.items()))},
                                  indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    out_edi = args.edi / "data" / "crosswalks" / "exhibit-cost-record.json"
    out_edi.parent.mkdir(parents=True, exist_ok=True)
    out_edi.write_text(json.dumps({"generated": stamp, "note": note, "edi_to_ecr": dict(sorted(edi_to_ecr.items()))},
                                  indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{len(edi_to_ecr)} EDI firms <-> {len(ecr_to_edi)} ECR firm pages")
    for fid, links in sorted(edi_to_ecr.items()):
        print(f"  {fid:40s} -> " + ", ".join(f"{l['slug']} ({l['records']})" for l in links))
    return 0


if __name__ == "__main__":
    sys.exit(main())
